insert into public.provinces(name, plate_no, slug, center_geog)
select sp.name, sp.plate_no, sp.slug, st_setsrid(st_makepoint(sp.lng, sp.lat), 4326)::geography
from seed_provinces sp
on conflict (plate_no) do update
set
  name = excluded.name,
  slug = excluded.slug,
  center_geog = excluded.center_geog;

insert into public.districts(province_id, name, slug, center_geog)
select p.id, sd.name, sd.slug, st_setsrid(st_makepoint(sd.lng, sd.lat), 4326)::geography
from seed_districts sd
join public.provinces p on p.slug = sd.province_slug
on conflict (province_id, slug) do update
set
  name = excluded.name,
  center_geog = excluded.center_geog;
